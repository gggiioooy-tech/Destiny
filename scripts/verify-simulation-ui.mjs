import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {createServer} from 'vite';
const vite=await createServer({optimizeDeps:{noDiscovery:true,include:[]},server:{middlewareMode:true,hmr:false},appType:'custom'});
try{
  const {default:Arena}=await vite.ssrLoadModule('/src/components/BattleArena.jsx');
  const {default:Simulation}=await vite.ssrLoadModule('/src/components/ExperimentalBattle.jsx');
  const {default:Results}=await vite.ssrLoadModule('/src/components/SimulationResults.jsx');
  const {default:Setup}=await vite.ssrLoadModule('/src/components/BattleSetup.jsx');
  const {STAT_FIELDS,finishSession}=await vite.ssrLoadModule('/src/lib/simulationWorkspace.js');
  const {prepareHeroes,createBattle,advanceBattle,defaultSkillPlans}=await vite.ssrLoadModule('/src/lib/experimentalBattle.js');
  const draft=prepareHeroes(),battle=advanceBattle(createBattle(draft));
  const html=renderToStaticMarkup(React.createElement(Arena,{draft,battle,running:true}));
  assert.equal((html.match(/class="battle-fighter battle-slot-/g)||[]).length,6);
  assert.equal((html.match(/role="progressbar"/g)||[]).length,6);
  assert.ok(html.includes('battle-floating'));assert.ok(html.includes('battle-skill-banner'));
  assert.ok(html.includes('aria-valuenow='));assert.ok(html.includes('no-referrer'));
  const passive={...battle,units:battle.units.map((u,i)=>i?u:{...u,name:'아리스',awakenMax:75,awakenGauge:50,awakenUsed:true,passiveAwakenActive:true})};
  const activePassiveHtml=renderToStaticMarkup(React.createElement(Arena,{draft,battle:passive}));assert.ok(activePassiveHtml.includes('각성 패시브 활성 · 50/75'));
  passive.units[0].passiveAwakenActive=false;passive.units[0].awakenGauge=0;
  assert.ok(renderToStaticMarkup(React.createElement(Arena,{draft,battle:passive})).includes('각성 패시브 종료'));
  for(const currentUser of [null,{role:'member'},{role:'admin',isOwner:false}])assert.equal(renderToStaticMarkup(React.createElement(Simulation,{currentUser})), '');
  const owner=renderToStaticMarkup(React.createElement(Simulation,{currentUser:{role:'admin',isOwner:true}}));
  assert.ok(owner.includes('176종 영웅 선택'));assert.ok(owner.includes('전투 종료'));assert.ok(owner.includes('영웅을 선택해 스탯 편집'));
  assert.equal((owner.match(/role="tab"/g)||[]).length,3);
  assert.ok(owner.includes('100회 비교'));assert.ok(owner.includes('계산 중지'));assert.ok(owner.includes('90% 정확도를 달성하지 못했습니다'));
  assert.ok(owner.includes('영웅 정보창 · 전투 전'));assert.ok(owner.includes('펫 잠재 4줄'));assert.ok(owner.includes('자동 계산된 전투 시작 수치'));
  assert.ok(owner.includes('펫 · +5강 · 풀스킬 강화'));assert.ok(!owner.includes('펫 강화 +'));assert.ok(!owner.includes('펫 스킬 강화'));
  for(const label of ['기본진형','밸런스진형','공격진형','보호진형'])assert.ok(owner.includes(label));
  const {default:Page}=await vite.ssrLoadModule('/src/components/ReplaySimulationPage.jsx');
  const page=renderToStaticMarkup(React.createElement(Page,{currentUser:{role:'admin',isOwner:true}}));
  for(const label of ['사이트에 저장된 전투','분석 JSON 열기','실전 기록 불러옴'])assert.ok(!page.includes(label));
  const setup=renderToStaticMarkup(React.createElement(Setup,{draft,plans:defaultSkillPlans(),seed:1,setDraft(){},setPlans(){},setSeed(){}}));
  assert.equal((setup.match(/type="number"/g)||[]).length,1);
  assert.equal((setup.match(/class="sim-seat /g)||[]).length,10);
  assert.ok(!setup.includes('영웅 스탯 입력'));assert.ok(!setup.includes('sim-stat-primary'));assert.equal((setup.match(/aria-haspopup="dialog"/g)||[]).length,6);
  assert.ok(setup.includes('이 배치에서 영웅 클릭'));assert.equal((setup.match(/예약 모두 해제/g)||[]).length,2);assert.ok(setup.includes('예약 없음 · 자동 스킬 선택'));
  assert.ok(setup.includes('자리 배치'));assert.ok(setup.includes('낮은 자리번호'));
  assert.ok(owner.indexOf('펫 잠재 4줄')<owner.indexOf('자리 배치'));

  for(const text of ['내 조합 저장','빠른 계산','공격·방어 교환'])assert.ok(owner.includes(text));
  const finished=finishSession({frames:[createBattle(draft)],cursor:0},advanceBattle);
  const resultHtml=renderToStaticMarkup(React.createElement(Results,{session:finished,onSeek(){}}));
  assert.equal((resultHtml.match(/<polyline/g)||[]).length,6);assert.ok(resultHtml.includes('행동 로그 팀 필터'));assert.ok(resultHtml.includes('이 장면 보기'));
  const stopped=renderToStaticMarkup(React.createElement(Arena,{draft,battle:{...battle,done:true,stopped:true,winner:null},running:false}));
  assert.ok(stopped.includes('사용자가 전투를 종료했습니다'));assert.ok(stopped.includes('전투 중단'));
  console.log('PASS six fighters, HP bars, tabs, single hero editor, presets, quick run, HP graphs, logs, manual stop and tier-four UI guard');
}finally{await vite.close();}
